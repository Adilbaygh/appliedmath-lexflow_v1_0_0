def normalize_language(language: str) -> str:
    """Validate and normalize a language code."""

    normalized = language.lower().strip()
    if normalized not in SUPPORTED_LANGUAGES:
        raise ValueError(
            f"Unsupported language {language!r}; choose one of {SUPPORTED_LANGUAGES}."
        )
    return normalized


def tr(key: str, language: str = "uz", **values: object) -> str:
    """Translate *key* and interpolate named values."""

    language = normalize_language(language)
    try:
        template = _TEXT[language][key]
    except KeyError as exc:
        raise KeyError(f"Missing translation key {key!r} for {language!r}.") from exc
    return template.format(**values)

